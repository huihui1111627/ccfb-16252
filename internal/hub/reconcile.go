package hub

import (
	"fmt"

	"airport-baggage/internal/domain"
)

func (s *Service) ReconcileFlight(flightID string, at domain.SimMinute) *domain.Reconciliation {
	s.DB.Mu.Lock()
	f := s.DB.Flights[flightID]
	if f == nil {
		s.DB.Mu.Unlock()
		return nil
	}
	rec := &domain.Reconciliation{
		ID:       fmt.Sprintf("REC-%s-%d", flightID, len(f.Reconciliations)+1),
		FlightID: flightID,
		At:       at,
		Passed:   true,
	}
	if problem, ok := s.DB.PlantedFaults[flightID]; ok {
		rec.PlantedProblem = problem
	}

	// Passengers currently ticketed on this flight.
	flightPax := map[string]*domain.Passenger{}
	for _, p := range s.DB.Passengers {
		if p.FlightID == flightID {
			flightPax[p.ID] = p
			if p.Status == domain.PaxBoarded {
				rec.BoardedPax++
			}
		}
	}

	physicalOnFlight := map[string]bool{}
	for _, cid := range f.Containers {
		c := s.DB.Containers[cid]
		if c == nil {
			continue
		}
		for _, tag := range c.BagTags {
			physicalOnFlight[tag] = true
		}
	}

	for _, p := range flightPax {
		if p.Status != domain.PaxBoarded {
			continue
		}
		for _, tag := range p.BagIDs {
			b := s.DB.Bags[tag]
			if b == nil {
				continue
			}
			rec.BoardedBags++
			onboard := physicalOnFlight[tag] || (b.FlightID == flightID && b.Status == domain.BagLoaded)
			if !onboard {
				rec.Passed = false
				actual := string(b.Status)
				if b.ContainerCode != "" {
					actual = fmt.Sprintf("%s @ %s L%d", b.Status, b.ContainerCode, b.Layer)
				}
				rec.Issues = append(rec.Issues, domain.ReconcileItem{
					BagTag: tag, PassengerName: p.Name, Type: "boarded_bag_missing",
					Detail: "旅客已登机，但行李未在本班机集装箱/舱单中", Expected: flightID, Actual: actual,
					Remediation: "立即按全流程轨迹定位并补装/转运",
				})
			}
		}
	}

	for _, b := range s.DB.Bags {
		if b.FlightID == flightID {
			p := s.DB.Passengers[b.PassengerID]
			boarded := p != nil && p.Status == domain.PaxBoarded
			if !boarded && (b.Status == domain.BagLoaded || b.Status == domain.BagMisloaded) {
				rec.Passed = false
				name := ""
				if p != nil {
					name = p.Name
				}
				rec.Issues = append(rec.Issues, domain.ReconcileItem{
					BagTag: b.Tag, PassengerName: name, Type: "nonboarded_bag_onboard",
					Detail: "旅客未登机/已取消，但行李仍显示装机", Expected: "offloaded", Actual: fmt.Sprintf("%s @ %s L%d", b.Status, b.ContainerCode, b.Layer),
					Remediation: "立即按集装箱层位卸载后复核",
				})
			}
		}

		// Physical container scan is authoritative for wrong-flight loads.
		if physicalOnFlight[b.Tag] && b.FlightID != flightID &&
			(b.Status == domain.BagLoaded || b.Status == domain.BagMisloaded) {
			rec.Passed = false
			p := s.DB.Passengers[b.PassengerID]
			name := b.PassengerName
			if p != nil {
				name = p.Name
			}
			rec.Issues = append(rec.Issues, domain.ReconcileItem{
				BagTag: b.Tag, PassengerName: name, Type: "wrong_flight",
				Detail: "行李实物在本班机集装箱，但报文航段指向另一航班", Expected: b.FlightID, Actual: flightID,
				Remediation: "卸机并按报文改装正确航班",
			})
		}
		if physicalOnFlight[b.Tag] && b.Status != domain.BagLoaded && b.Status != domain.BagMisloaded {
			// Container count and bag state diverged; treat as serious.
			rec.Passed = false
			rec.Issues = append(rec.Issues, domain.ReconcileItem{
				BagTag: b.Tag, Type: "container_state_mismatch",
				Detail: "集装箱扫描清单与行李状态不一致", Expected: string(domain.BagLoaded), Actual: string(b.Status),
				Remediation: "重新扫描集装箱并校正舱单",
			})
		}
		if b.FlightID == flightID && b.Status == domain.BagLoaded {
			rec.OnboardBags++
		}
	}
	// Count physical bags even if their flight ID is wrong.
	rec.OnboardBags = len(physicalOnFlight)

	f.Reconciliations = append(f.Reconciliations, *rec)
	latest := f.Reconciliations[len(f.Reconciliations)-1]
	if rec.Passed {
		f.ReleaseBlocked = false
		if f.Status != domain.FlightDeparted {
			f.Status = domain.FlightClosing
		}
		latest.Note = "机上行李/已登机旅客/未登机旅客三方一致"
	} else {
		f.ReleaseBlocked = true
		f.Released = false
		f.Status = domain.FlightBlocked
	}
	msg := s.lockedMessage(at, TopicReconcile, "DOOR_CLOSE_RECONCILE", flightID, map[string]interface{}{
		"passed": rec.Passed, "issues": len(rec.Issues), "boardedPax": rec.BoardedPax,
		"plantedProblem": rec.PlantedProblem,
	})
	s.DB.Mu.Unlock()
	s.finishRecord(msg)

	if rec.Passed {
		s.AddAlert(at, "success", TopicReconcile, "关舱核对通过", fmt.Sprintf("%s：已登机旅客 %d 人，机上实物 %d 件，三方一致，可放行", f.Number, rec.BoardedPax, rec.OnboardBags), "flight", flightID)
	} else {
		s.AddAlert(at, "critical", TopicReconcile, "关舱核对未通过，航班禁止放行", fmt.Sprintf("%s 发现 %d 项不一致；系统已拦截放行并生成卸载/补装指令", f.Number, len(rec.Issues)), "flight", flightID)
	}
	return &latest
}

// RemediateFlight executes the exact handling instruction generated by a
// failed reconciliation. The next reconciliation verifies the result.
func (s *Service) RemediateFlight(flightID string, at domain.SimMinute) int {
	s.DB.Mu.RLock()
	rec := s.DB.LatestReconciliation(flightID)
	if rec == nil || rec.Passed {
		s.DB.Mu.RUnlock()
		return 0
	}
	items := append([]domain.ReconcileItem{}, rec.Issues...)
	s.DB.Mu.RUnlock()

	handled := 0
	for _, item := range items {
		tag := item.BagTag
		switch item.Type {
		case "nonboarded_bag_onboard":
			s.OffloadBag(tag, at, "关舱核对拦截：旅客未登机，强制卸载")
			handled++
		case "wrong_flight":
			s.OffloadBag(tag, at, "关舱核对拦截：错装航班，卸机重分")
			s.DB.Mu.Lock()
			if b := s.DB.Bags[tag]; b != nil {
				b.Status = domain.BagRecovered
				b.ReadyAt = 0
				if f := s.DB.Flights[b.FlightID]; f != nil {
					b.ChuteID = f.ChuteID
				}
			}
			s.DB.Mu.Unlock()
			s.LoadBag(tag, at)
			handled++
		case "boarded_bag_missing":
			// Bring whatever physical state it is in to the correct flight.
			s.DB.Mu.Lock()
			b := s.DB.Bags[tag]
			if b != nil {
				if b.Status == domain.BagLoaded || b.Status == domain.BagMisloaded {
					if b.ContainerID != "" {
						removeBagFromContainerLocked(s, b)
					}
				}
				b.FlightID = flightID
				b.Status = domain.BagRecovered
				b.ChuteID = s.DB.Flights[flightID].ChuteID
				b.ReadyAt = 0
				AddBagEvent(b, at, domain.EventRemediation, "关舱核对后找到/召回行李，立即补装本班机", "补装")
			}
			s.DB.Mu.Unlock()
			s.LoadBag(tag, at)
			handled++
		case "container_state_mismatch":
			s.DB.Mu.Lock()
			b := s.DB.Bags[tag]
			if b != nil {
				b.Status = domain.BagRecovered
			}
			s.DB.Mu.Unlock()
			s.LoadBag(tag, at)
			handled++
		}
	}
	if handled > 0 {
		s.AddAlert(at, "info", TopicReconcile, "问题行李处置完成，等待复核", fmt.Sprintf("%s 已生成并执行 %d 条处置，2 分钟后重新关舱核对", flightID, handled), "flight", flightID)
		s.RecordMessage(at, TopicReconcile, "REMEDIATION_EXECUTED", flightID, map[string]interface{}{"handled": handled})
	}
	return handled
}

func (s *Service) ReleaseFlight(flightID string, at domain.SimMinute) bool {
	s.DB.Mu.Lock()
	f := s.DB.Flights[flightID]
	rec := s.DB.LatestReconciliation(flightID)
	if f == nil || rec == nil || !rec.Passed || f.ReleaseBlocked {
		s.DB.Mu.Unlock()
		return false
	}
	f.Released = true
	f.Status = domain.FlightClosing
	msg := s.lockedMessage(at, TopicDeparture, "FLIGHT_RELEASED", flightID, map[string]interface{}{"flightId": flightID})
	s.DB.Mu.Unlock()
	s.finishRecord(msg)
	return true
}

func (s *Service) DepartFlight(flightID string, at domain.SimMinute) bool {
	s.DB.Mu.Lock()
	f := s.DB.Flights[flightID]
	if f == nil || !f.Released || f.Status == domain.FlightDeparted {
		s.DB.Mu.Unlock()
		return false
	}
	t := at
	f.Status = domain.FlightDeparted
	f.ActualAt = &t
	if at > f.ScheduledAt {
		f.DelayMinutes = at - f.ScheduledAt
		if f.DelayMinutes > 5 {
			f.Status = domain.FlightDelayed
			// Keep departed semantics while exposing delay status? Use departed and delay field.
			f.Status = domain.FlightDeparted
		}
	}
	departed := 0
	for _, b := range s.DB.Bags {
		if b.FlightID != flightID {
			continue
		}
		if b.Status == domain.BagLoaded {
			b.Status = domain.BagDeparted
			b.DepartedAt = &t
			departed++
			expected := fmt.Sprintf("depart_on_%s", flightID)
			if b.ExpectedDisposition == expected {
				ok := true
				b.Correct = &ok
			}
		} else if b.Status == domain.BagOffloaded || b.Status == domain.BagVoided {
			if p := s.DB.Passengers[b.PassengerID]; p != nil && (p.Status == domain.PaxNoShow || p.Status == domain.PaxCancelled) {
				ok := true
				b.Correct = &ok
			}
		}
	}
	msg := s.lockedMessage(at, TopicDeparture, "FLIGHT_DEPARTED", flightID, map[string]interface{}{"flightId": flightID, "bagsDeparted": departed, "delayMinutes": f.DelayMinutes})
	s.DB.Mu.Unlock()
	s.finishRecord(msg)
	s.AddAlert(at, "info", TopicDeparture, "航班起飞", fmt.Sprintf("%s 已起飞，%d 件行李随机离港", f.Number, departed), "flight", flightID)
	return true
}

func (s *Service) AuditFinalDispositions(at domain.SimMinute) int {
	audited := 0
	s.DB.Mu.Lock()
	for _, b := range s.DB.Bags {
		if b.Correct != nil {
			continue
		}
		ok := false
		terminal := true
		switch {
		case b.Status == domain.BagDeparted:
			ok = b.ExpectedDisposition == fmt.Sprintf("depart_on_%s", b.FlightID) || b.TransferOutcome == "rebooked" || b.TransferOutcome == "original"
		case b.Status == domain.BagVoided:
			if p := s.DB.Passengers[b.PassengerID]; p != nil {
				ok = p.Status == domain.PaxCancelled
			}
		case b.Status == domain.BagOffloaded:
			if p := s.DB.Passengers[b.PassengerID]; p != nil {
				ok = p.Status == domain.PaxNoShow || p.Status == domain.PaxCancelled
			}
		case b.Status == domain.BagFailed:
			ok = false
		case b.UnknownScan && (b.Status == domain.BagMissingMessage || b.Status == domain.BagExceptionChute):
			ok = true // safely contained and escalated
			b.ExpectedDisposition = "exception_contained_and_verified"
		case b.Status == domain.BagExceptionChute:
			ok = true
		default:
			// Still in check-in/sorter/loading flow: do not publish a
			// misleading correctness verdict before the lifecycle is terminal.
			terminal = false
		}
		if !terminal {
			continue
		}
		b.Correct = &ok
		if ok {
			audited++
		}
	}
	s.DB.Mu.Unlock()
	s.RecordMessage(at, TopicReconcile, "FINAL_AUDIT", "day", map[string]interface{}{"newlyAudited": audited})
	return audited
}
